#!/usr/bin/env node
// Generate the workbench's secret-free opencode config from the host config.
// The host provider catalog is canonical; only sandbox policy differs here.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

const [, , sourcePath, outputPath] = process.argv;

function usage() {
  console.error("usage: generate-opencode-config.mjs SOURCE_JSONC OUTPUT_JSONC");
  process.exit(2);
}

function stripJsonc(source) {
  let result = "";
  let inString = false;
  let escaped = false;

  for (let i = 0; i < source.length; i += 1) {
    const character = source[i];
    const next = source[i + 1];

    if (inString) {
      result += character;
      if (escaped) {
        escaped = false;
      } else if (character === "\\") {
        escaped = true;
      } else if (character === '"') {
        inString = false;
      }
      continue;
    }

    if (character === '"') {
      inString = true;
      result += character;
    } else if (character === "/" && next === "/") {
      i += 1;
      while (i + 1 < source.length && source[i + 1] !== "\n") i += 1;
      result += "\n";
    } else if (character === "/" && next === "*") {
      i += 2;
      while (i < source.length && !(source[i] === "*" && source[i + 1] === "/")) {
        if (source[i] === "\n") result += "\n";
        i += 1;
      }
    } else {
      result += character;
    }
  }

  // JSONC permits trailing commas. Remove them without touching string values.
  let withoutTrailingCommas = "";
  inString = false;
  escaped = false;
  for (let i = 0; i < result.length; i += 1) {
    const character = result[i];
    if (inString) {
      withoutTrailingCommas += character;
      if (escaped) {
        escaped = false;
      } else if (character === "\\") {
        escaped = true;
      } else if (character === '"') {
        inString = false;
      }
      continue;
    }
    if (character === '"') {
      inString = true;
      withoutTrailingCommas += character;
    } else if (character === ",") {
      let next = i + 1;
      while (/\s/.test(result[next] ?? "")) next += 1;
      if (result[next] !== "]" && result[next] !== "}") withoutTrailingCommas += character;
    } else {
      withoutTrailingCommas += character;
    }
  }
  return withoutTrailingCommas;
}

function readJsonc(path) {
  return JSON.parse(stripJsonc(readFileSync(path, "utf8")));
}

function main() {
  if (!sourcePath || !outputPath) usage();

  const host = readJsonc(sourcePath);
  if (!host.providers || typeof host.providers !== "object") {
    throw new Error(`host config has no providers object: ${sourcePath}`);
  }

  const workbench = {
    $schema: host.$schema,
    share: host.share,
    // The image pins opencode; self-update would fight the pin.
    update: "disable",
    model: host.model,
    // These are the sandbox policy differences from the host config.
    permissions: [
      { action: "read", resource: "*.env", effect: "deny" },
      { action: "read", resource: "*.env.*", effect: "deny" },
      { action: "read", resource: "*.env.example", effect: "allow" },
      { action: "external_directory", resource: "*", effect: "allow" },
      { action: "shell", resource: "git push --force*", effect: "deny" },
      { action: "shell", resource: "git push -f*", effect: "deny" },
    ],
    // TinyFish serves searches keyless in the sandbox and avoids an interactive
    // provider picker in autonomous sessions.
    websearch: { provider: "tinyfish" },
    providers: host.providers,
  };

  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(
    outputPath,
    "// Generated by generate-opencode-config.mjs - do not edit.\n" +
      `${JSON.stringify(workbench, null, 2)}\n`,
  );
}

try {
  main();
} catch (error) {
  console.error(`opencode config generation failed: ${error.message}`);
  process.exit(1);
}
